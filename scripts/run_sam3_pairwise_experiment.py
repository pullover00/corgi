#!/usr/bin/env python3
"""Run isolated SAM2/SAM3 proposal + SAM3.1 tracking experiments.

The runner deliberately reuses reconstruction and rendering artifacts from the
fixed no-splat IoU/area-gate baseline.  This keeps the input pairs and geometry
identical while changing only the proposal/tracking components under study.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import time
import traceback
from pathlib import Path

import numpy as np
from PIL import Image

from ocmask.changesim import MetricAccumulator, load_manifest, normalize_target
from ocmask.config import load_config
from ocmask.stages.dinov2_motion import replay_baseline_labels
from ocmask.stages.sam31_backend import Sam31MaskTracker
from ocmask.stages.sam2_tracking_backend import Sam2MaskTracker
from ocmask.stages.sam3_pairwise import (
    load_cached_inputs,
    load_proposal_cache,
    load_selected_sam2_masks,
    proposals_to_objects,
    run_cached_pair,
    save_proposal_cache,
)
from ocmask.stages.sam3_proposals import Sam3AutomaticMaskGenerator
from ocmask.io import save_image, save_json
from ocmask.visualization import colorize


def _arguments() -> argparse.Namespace:
    parser = argparse.ArgumentParser()
    parser.add_argument("--config", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument(
        "--limit",
        type=int,
        default=None,
        help="Run only the first N fixed pairs (for an implementation smoke test).",
    )
    parser.add_argument(
        "--pair-id",
        action="append",
        default=[],
        help=(
            "Run one named fixed-selection pair. Repeat for multiple pairs; "
            "cannot be combined with --limit."
        ),
    )
    parser.add_argument(
        "--validate-only",
        action="store_true",
        help=(
            "Validate the revision-4 input contract, proposal caches, and "
            "fingerprints without loading a GPU tracker."
        ),
    )
    parser.add_argument(
        "--cache-only",
        action="store_true",
        help="Keep reusable masks/ledgers/labels but omit qualitative GT/color images.",
    )
    parser.add_argument(
        "--proposals-only",
        action="store_true",
        help=(
            "Generate/validate durable SAM3 proposal caches and stop before "
            "loading a tracking model. Intended for resumable cache warming."
        ),
    )
    parser.add_argument(
        "--assume-same-place-classification",
        action="store_true",
        help=(
            "Verify the parent baseline's pre-flight replay assuming its "
            "artifacts were produced by a current pipeline.py run (which "
            "applies masks.same_place in stage-03/06 classification), "
            "instead of this repository's default assumption of an older, "
            "frozen baseline that predates that check. Only pass this for a "
            "parent you know was freshly generated by current pipeline.py "
            "(e.g. a ground-contact-corrected artifact) -- every existing "
            "frozen baseline in this repository needs the default (unset)."
        ),
    )
    return parser.parse_args()


def _sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as stream:
        for block in iter(lambda: stream.read(1024 * 1024), b""):
            digest.update(block)
    return digest.hexdigest()


def _config_hash(config: dict) -> str:
    return hashlib.sha256(
        json.dumps(config, sort_keys=True).encode("utf-8")
    ).hexdigest()


def _implementation_hash() -> str:
    """Hash every local source file that can change this experiment's result."""

    repository = Path(__file__).resolve().parents[1]
    paths = [
        Path(__file__).resolve(),
        repository / "src/ocmask/stages/sam3_pairwise.py",
        repository / "src/ocmask/stages/sam31_backend.py",
        repository / "src/ocmask/stages/sam2_tracking_backend.py",
        repository / "src/ocmask/stages/dinov2_motion.py",
        repository / "src/ocmask/masks.py",
        repository / "src/ocmask/adapters/sam2.py",
    ]
    digest = hashlib.sha256()
    for path in paths:
        digest.update(str(path.relative_to(repository)).encode("utf-8"))
        digest.update(bytes.fromhex(_sha256(path)))
    return digest.hexdigest()


def _execution_hash(
    config: dict,
    config_hash: str,
    parent_hash: str,
    implementation_hash: str,
) -> str:
    """Bind result caches to configuration, code, parent, and checkpoint."""

    checkpoint_identity = {
        key: config.get(key)
        for key in (
            "sam3_source_commit",
            "sam3_image_checkpoint_sha256",
            "sam31_checkpoint_sha256",
        )
        if config.get(key) is not None
    }
    payload = {
        "config_sha256": config_hash,
        "parent_report_sha256": parent_hash,
        "implementation_sha256": implementation_hash,
        "checkpoint_identity": checkpoint_identity,
    }
    return hashlib.sha256(
        json.dumps(payload, sort_keys=True).encode("utf-8")
    ).hexdigest()


def _objects_hash(objects) -> str:
    """Hash proposal pixels and relevant metadata in original proposal order."""

    digest = hashlib.sha256()
    for obj in objects:
        mask = np.ascontiguousarray(obj.mask, dtype=bool)
        digest.update(str(mask.shape).encode("utf-8"))
        digest.update(np.packbits(mask.reshape(-1)).tobytes())
        digest.update(str(float(obj.score)).encode("utf-8"))
        digest.update(
            json.dumps(obj.metadata, sort_keys=True, default=str).encode("utf-8")
        )
    return digest.hexdigest()


def _pair_fingerprint(
    artifact: Path,
    source_proposals,
    target_proposals,
) -> str:
    """Fingerprint every immutable per-pair input that affects inference."""

    digest = hashlib.sha256()
    for name in (
        "render_0_to_1.png",
        "render_clean_to_1.png",
        "reconstruction.npz",
        "geometry.npz",
        "config.json",
    ):
        path = artifact / name
        digest.update(name.encode("utf-8"))
        digest.update(bytes.fromhex(_sha256(path)))
    digest.update(bytes.fromhex(_objects_hash(source_proposals)))
    digest.update(bytes.fromhex(_objects_hash(target_proposals)))
    return digest.hexdigest()


def _table3(metrics: dict) -> dict:
    """Present aggregate IoU values in the same percentage layout as Table 3."""

    return {
        "binary": {
            "changed": 100.0 * metrics["binary"]["changed"]["iou"],
            "unchanged": 100.0 * metrics["binary"]["unchanged"]["iou"],
            "miou": 100.0 * metrics["binary_miou"],
        },
        "multiclass": {
            **{
                name: 100.0 * metrics["multiclass"][name]["iou"]
                for name in (
                    "added",
                    "removed",
                    "moved",
                    "replaced",
                    "unchanged",
                )
            },
            "miou": 100.0 * metrics["multiclass_miou"],
        },
    }


def _validate_experiment_config(config: dict) -> None:
    """Refuse historical configs that can reintroduce the debug-overlay bug."""

    if int(config.get("adapter_revision", 0)) < 4:
        raise ValueError("SAM3 experiments require adapter_revision >= 4")
    contract = config.get("input_contract", {})
    expected = {
        "source_render": "render_0_to_1.png",
        "clean_render": "render_clean_to_1.png",
        "target_image": "reconstruction.npz::images[1]",
        "forbid_sam_debug_inputs": True,
    }
    mismatches = {
        key: {"expected": value, "actual": contract.get(key)}
        for key, value in expected.items()
        if contract.get(key) != value
    }
    if mismatches:
        raise ValueError(f"invalid raw-render input contract: {mismatches}")


def _validate_parent(
    baseline_dir: Path,
) -> tuple[dict, list[str], dict[str, dict]]:
    """Verify that the immutable parent is the complete fixed ten-pair run."""

    report_path = baseline_dir / "report.json"
    report = json.loads(report_path.read_text(encoding="utf-8"))
    selection = json.loads(
        (baseline_dir / "selection.json").read_text(encoding="utf-8")
    )
    selected_ids = list(selection["ids"])
    records = {record["id"]: record for record in report["pairs"]}
    if report.get("failures"):
        raise RuntimeError("parent evaluation contains failures")
    if report["protocol"]["pairs_succeeded"] != len(selected_ids):
        raise RuntimeError("parent evaluation is incomplete")
    if set(selected_ids) != set(records):
        raise RuntimeError("parent report and selection contain different pairs")
    return report, selected_ids, records


def _verify_baseline_replays(
    selected_ids: list[str],
    baseline_records: dict[str, dict],
    assume_same_place_classification: bool = False,
) -> None:
    """Fail before inference if cached artifacts cannot reproduce the baseline.

    ``assume_same_place_classification`` must be ``False`` (the default) for
    every ordinary run against this repository's existing frozen baselines:
    they were generated by a ``pipeline.py`` that did not yet apply
    ``masks.same_place`` in its stage-03/06 classification, and
    ``replay_baseline_labels``'s default reproduces exactly that (verified
    directly across 1038 real cached pairs, see
    ``scripts/verify_replay_baseline_labels.py``). Set it only when the
    parent baseline is known to have been produced by a current
    ``pipeline.py`` run that does include ``same_place`` -- e.g. a
    ground-contact-corrected pair's freshly regenerated artifacts -- via
    ``--assume-same-place-classification``.
    """

    for number, pair_id in enumerate(selected_ids, 1):
        artifact = Path(baseline_records[pair_id]["artifacts"])
        replay = replay_baseline_labels(
            artifact, apply_same_place_filter=assume_same_place_classification
        )
        saved = np.asarray(Image.open(artifact / "labels.png"), dtype=np.uint8)
        difference = int(np.count_nonzero(replay != saved))
        # Full-dataset cache warming may reuse rendering artifacts frozen
        # immediately before the same-place classification correction while
        # also producing new artifacts with the current convention. Both are
        # exact, versioned replays; select the matching convention per pair.
        if difference:
            alternate = replay_baseline_labels(
                artifact,
                apply_same_place_filter=not assume_same_place_classification,
            )
            alternate_difference = int(np.count_nonzero(alternate != saved))
            if alternate_difference == 0:
                replay = alternate
                difference = 0
        if difference:
            raise RuntimeError(
                f"{pair_id}: parent replay differs at {difference} pixels"
            )
        print(
            f"[validation {number}/{len(selected_ids)}] {pair_id}: exact replay",
            flush=True,
        )


def _generate_sam3_caches(
    config: dict,
    output: Path,
    selected_ids: list[str],
    baseline_records: dict[str, dict],
) -> None:
    """Generate all SAM3 proposals first, then release its image model.

    SAM3 proposal inference and SAM3.1 video tracking are kept sequential so
    both large models never need to occupy the 16 GB GPU at the same time.
    """

    if config["proposal_backend"] != "sam3_point_grid":
        return
    direction = config.get("direction", "forward")
    if config.get("proposal_cache_parent"):
        # A corrected tracker experiment must not rerun the expensive SAM3
        # image proposal model.  Validate every immutable cache up front so a
        # missing file fails before SAM3.1 tracking starts.
        parent = Path(config["proposal_cache_parent"]).resolve()
        for number, pair_id in enumerate(selected_ids, 1):
            cache_dir = parent / "pairs" / pair_id / "proposal_cache"
            required = (
                cache_dir / "source.npz",
                cache_dir / "target.npz",
                cache_dir / "metadata.json",
            )
            missing = [str(path) for path in required if not path.exists()]
            if missing:
                raise FileNotFoundError(
                    f"{pair_id}: missing reusable proposal caches: {missing}"
                )
            print(
                f"[proposals {number}/{len(selected_ids)}] "
                f"{pair_id} (reused from {parent})",
                flush=True,
            )
        return

    proposal_config = config["proposals"]
    generator = Sam3AutomaticMaskGenerator(
        config["sam3_image_checkpoint"],
        points_per_side=proposal_config["points_per_side"],
        points_per_batch=proposal_config["points_per_batch"],
        pred_iou_threshold=proposal_config["pred_iou_threshold"],
        stability_threshold=proposal_config["stability_threshold"],
        stability_offset=proposal_config["stability_offset"],
        crop_layers=proposal_config["crop_layers"],
        crop_downscale_factor=proposal_config["crop_downscale_factor"],
        box_nms_threshold=proposal_config["box_nms_threshold"],
        crop_nms_threshold=proposal_config["crop_nms_threshold"],
        minimum_mask_area=proposal_config["minimum_mask_area"],
        multimask_output=proposal_config["multimask_output"],
    )
    try:
        for number, pair_id in enumerate(selected_ids, 1):
            cache_dir = output / "pairs" / pair_id / "proposal_cache"
            source_cache = cache_dir / "source.npz"
            target_cache = cache_dir / "target.npz"
            if source_cache.exists() and target_cache.exists():
                print(
                    f"[proposals {number}/{len(selected_ids)}] {pair_id} (cached)",
                    flush=True,
                )
                continue
            artifact = Path(baseline_records[pair_id]["artifacts"])
            parent_config = json.loads((artifact / "config.json").read_text(encoding="utf-8"))
            inputs = load_cached_inputs(
                artifact, direction=direction, geometry_config=parent_config["geometry"]
            )
            started = time.perf_counter()
            if not source_cache.exists():
                source = generator.generate(inputs.source_render)
                save_proposal_cache(
                    source_cache, source, inputs.source_render.shape[:2]
                )
            else:
                source = load_proposal_cache(source_cache)
            if not target_cache.exists():
                target = generator.generate(inputs.target_image)
                save_proposal_cache(
                    target_cache, target, inputs.target_image.shape[:2]
                )
            else:
                target = load_proposal_cache(target_cache)
            save_json(
                cache_dir / "metadata.json",
                {
                    "source_count": len(source),
                    "target_count": len(target),
                    "elapsed_seconds": time.perf_counter() - started,
                    "ground_truth_used": False,
                },
            )
            print(
                f"[proposals {number}/{len(selected_ids)}] {pair_id}: "
                f"{len(source)} source, {len(target)} target",
                flush=True,
            )
    finally:
        generator.release()


def _pair_proposals(
    config: dict, pair_dir: Path, artifact: Path
):
    """Load either exact cached SAM2 proposals or cached SAM3 proposals."""

    if config["proposal_backend"] == "cached_sam2":
        return load_selected_sam2_masks(artifact)
    if config.get("proposal_cache_parent"):
        cache_dir = (
            Path(config["proposal_cache_parent"]).resolve()
            / "pairs"
            / pair_dir.name
            / "proposal_cache"
        )
    else:
        cache_dir = pair_dir / "proposal_cache"
    return (
        proposals_to_objects(load_proposal_cache(cache_dir / "source.npz")),
        proposals_to_objects(load_proposal_cache(cache_dir / "target.npz")),
    )


def main() -> int:
    args = _arguments()
    config = load_config(args.config)
    _validate_experiment_config(config)
    baseline_dir = Path(config["parent_evaluation"]).resolve()
    baseline, selected_ids, baseline_records = _validate_parent(baseline_dir)
    if args.pair_id and args.limit is not None:
        raise ValueError("--pair-id and --limit cannot be combined")
    if args.pair_id:
        unknown = [pair_id for pair_id in args.pair_id if pair_id not in selected_ids]
        if unknown:
            raise ValueError(
                f"--pair-id values are outside the fixed selection: {unknown}"
            )
        # Preserve the explicit command-line order while rejecting duplicates.
        selected_ids = list(dict.fromkeys(args.pair_id))
    if args.limit is not None:
        if args.limit < 1:
            raise ValueError("--limit must be positive")
        selected_ids = selected_ids[: args.limit]

    manifest = {
        pair.pair_id: pair
        for pair in load_manifest(Path(config["manifest"]))
    }
    missing = [pair_id for pair_id in selected_ids if pair_id not in manifest]
    if missing:
        raise RuntimeError(f"selected pairs missing from manifest: {missing}")

    args.output.mkdir(parents=True, exist_ok=True)
    (args.output / "pairs").mkdir(exist_ok=True)
    config_hash = _config_hash(config)
    parent_hash = _sha256(baseline_dir / "report.json")
    implementation_hash = _implementation_hash()
    execution_hash = _execution_hash(
        config, config_hash, parent_hash, implementation_hash
    )
    save_json(
        args.output / "experiment.json",
        {
            "experiment_id": config["experiment_id"],
            "config": str(args.config.resolve()),
            "config_sha256": config_hash,
            "parent_evaluation": str(baseline_dir),
            "parent_report_sha256": parent_hash,
            "implementation_sha256": implementation_hash,
            "execution_sha256": execution_hash,
            "selection": selected_ids,
            "ground_truth_used_in_inference": False,
        },
    )
    save_json(args.output / "selection.json", {"ids": selected_ids})

    # This assertion is independent of the new models and guarantees that the
    # cached baseline is being interpreted exactly before running an ablation.
    _verify_baseline_replays(
        selected_ids, baseline_records, args.assume_same_place_classification
    )
    _generate_sam3_caches(
        config, args.output, selected_ids, baseline_records
    )

    if args.proposals_only:
        save_json(
            args.output / "proposal_cache_complete.json",
            {
                "execution_sha256": execution_hash,
                "pairs": selected_ids,
                "pair_count": len(selected_ids),
            },
        )
        print(
            f"Proposal cache complete for {len(selected_ids)} pairs; "
            "tracking model was not loaded.",
            flush=True,
        )
        return 0

    if args.validate_only:
        validation_records = []
        for pair_id in selected_ids:
            artifact = Path(baseline_records[pair_id]["artifacts"])
            pair_dir = args.output / "pairs" / pair_id
            pair_dir.mkdir(parents=True, exist_ok=True)
            parent_config = json.loads((artifact / "config.json").read_text(encoding="utf-8"))
            inputs = load_cached_inputs(
                artifact,
                direction=config.get("direction", "forward"),
                geometry_config=parent_config["geometry"],
            )
            source_proposals, target_proposals = _pair_proposals(
                config, pair_dir, artifact
            )
            validation_records.append(
                {
                    "id": pair_id,
                    "pair_fingerprint_sha256": _pair_fingerprint(
                        artifact, source_proposals, target_proposals
                    ),
                    "source_proposals": len(source_proposals),
                    "target_proposals": len(target_proposals),
                    "input_provenance": inputs.input_provenance,
                }
            )
        save_json(
            args.output / "input_validation.json",
            {
                "passed": True,
                "adapter_revision": config["adapter_revision"],
                "execution_sha256": execution_hash,
                "pairs": validation_records,
            },
        )
        print(
            f"Validated {len(validation_records)} revision-4 pair inputs "
            f"without GPU inference.",
            flush=True,
        )
        return 0

    tracking = config["tracking"]
    # The baseline minimum area is read once; all ten parent pairs share this
    # versioned value, and keeping it fixed isolates the model substitution.
    first_artifact = Path(baseline_records[selected_ids[0]]["artifacts"])
    baseline_config = json.loads(
        (first_artifact / "config.json").read_text(encoding="utf-8")
    )
    if config["tracking_backend"] == "sam2":
        tracker = Sam2MaskTracker(baseline_config)
    elif config["tracking_backend"].startswith("sam3.1"):
        tracker = Sam31MaskTracker(
            config["sam31_checkpoint"],
            batch_size=tracking["batch_size"],
            minimum_mask_area=baseline_config["tracking"]["minimum_mask_area"],
            minimum_object_score=tracking["minimum_object_score"],
            use_fa3=tracking["use_flash_attention_3"],
            use_rope_real=tracking["use_real_rope"],
            batching_mode=tracking.get("batching_mode", "overlap_safe"),
            disable_output_non_overlap=tracking.get(
                "disable_output_non_overlap", True
            ),
            model_max_num_objects=tracking.get("model_max_num_objects"),
        )
    else:
        raise ValueError(
            f"unsupported tracking_backend: {config['tracking_backend']}"
        )

    accumulator = MetricAccumulator()
    records: list[dict] = []
    failures: list[dict] = []
    experiment_started = time.perf_counter()
    try:
        for number, pair_id in enumerate(selected_ids, 1):
            pair_started = time.perf_counter()
            pair_dir = args.output / "pairs" / pair_id
            pair_dir.mkdir(parents=True, exist_ok=True)
            result_path = pair_dir / "result.json"
            artifact = Path(baseline_records[pair_id]["artifacts"])
            source_proposals, target_proposals = _pair_proposals(
                config, pair_dir, artifact
            )
            pair_fingerprint = _pair_fingerprint(
                artifact, source_proposals, target_proposals
            )
            if result_path.exists():
                cached = json.loads(result_path.read_text(encoding="utf-8"))
                if (
                    cached.get("execution_sha256") == execution_hash
                    and cached.get("pair_fingerprint_sha256")
                    == pair_fingerprint
                ):
                    accumulator.add_confusion(cached["confusion"])
                    records.append(cached)
                    print(
                        f"[tracking {number}/{len(selected_ids)}] "
                        f"{pair_id} (cached)",
                        flush=True,
                    )
                    continue

            try:
                import torch

                if torch.cuda.is_available():
                    torch.cuda.reset_peak_memory_stats()
                labels, diagnostics = run_cached_pair(
                    artifact,
                    pair_dir,
                    tracker,
                    source_proposals,
                    target_proposals,
                    direction=config.get("direction", "forward"),
                )

                # Ground truth is loaded only after the complete prediction has
                # been composed and saved; it cannot influence inference.
                target = normalize_target(manifest[pair_id].target)
                pair_accumulator = MetricAccumulator()
                pair_accumulator.add(labels, target)
                accumulator.add_confusion(pair_accumulator.confusion)
                if not args.cache_only:
                    save_image(pair_dir / "labels_color.png", colorize(labels))
                    save_image(pair_dir / "ground_truth.png", colorize(target))
                record = {
                    "id": pair_id,
                    "status": "success",
                    "artifacts": str(pair_dir.resolve()),
                    "parent_artifacts": str(artifact.resolve()),
                    "config_sha256": config_hash,
                    "implementation_sha256": implementation_hash,
                    "execution_sha256": execution_hash,
                    "pair_fingerprint_sha256": pair_fingerprint,
                    "confusion": pair_accumulator.confusion.tolist(),
                    "diagnostics": diagnostics,
                    "elapsed_seconds": time.perf_counter() - pair_started,
                    "peak_vram_mib": (
                        float(torch.cuda.max_memory_allocated() / 1024**2)
                        if torch.cuda.is_available()
                        else None
                    ),
                }
                save_json(result_path, record)
                records.append(record)
                print(
                    f"[tracking {number}/{len(selected_ids)}] {pair_id}: "
                    f"{diagnostics['final_object_counts']}",
                    flush=True,
                )
            except Exception as exc:
                failure = {
                    "id": pair_id,
                    "error": f"{type(exc).__name__}: {exc}",
                    "traceback": traceback.format_exc(),
                }
                failures.append(failure)
                save_json(pair_dir / "failure.json", failure)
                print(
                    f"[tracking {number}/{len(selected_ids)}] "
                    f"{pair_id}: FAILED: {exc}",
                    flush=True,
                )
    finally:
        tracker.release()

    if not records:
        raise RuntimeError("all experiment pairs failed")
    metrics = accumulator.compute()
    report = {
        "protocol": {
            "dataset": "ChangeSim",
            "experiment": config["experiment_id"],
            "parent_fraction": baseline["protocol"]["fraction"],
            "seed": baseline["protocol"]["seed"],
            "pairs_selected": len(selected_ids),
            "pairs_succeeded": len(records),
        },
        "metrics": metrics,
        "table3_iou_percent": _table3(metrics),
        "parent_table3_iou_percent": baseline["table3_iou_percent"],
        "elapsed_seconds": time.perf_counter() - experiment_started,
        "failures": failures,
        "pairs": records,
        "provenance": {
            "parent_report_sha256": parent_hash,
            "config_sha256": config_hash,
            "implementation_sha256": implementation_hash,
            "execution_sha256": execution_hash,
            "ground_truth_used_in_inference": False,
            "baseline_replay_exact_for_all_pairs": True,
            "proposal_backend": config["proposal_backend"],
            "tracking_backend": config["tracking_backend"],
        },
    }
    save_json(args.output / "report.json", report)
    print(json.dumps(report["table3_iou_percent"], indent=2), flush=True)
    if failures:
        print(f"Completed with {len(failures)} failed pairs.", flush=True)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
